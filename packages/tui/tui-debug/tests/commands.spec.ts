import { describe, expect, it } from 'vitest'
import { DEBUG_KEY_COMMANDS, parseDebugCommand } from '../src/commands.ts'

describe('TUI debug commands', () => {
  it('parses break, condition, logpoint, execution, and session commands', () => {
    expect(parseDebugCommand(':break src/a.ts:4 if x > 1')).toMatchObject({ name: 'break', file: 'src/a.ts', line: 4, condition: 'x > 1' })
    expect(parseDebugCommand(':break src/a.ts:4 log x={x}')).toMatchObject({ name: 'break', logMessage: 'x={x}' })
    expect(parseDebugCommand(':next')).toEqual({ name: 'next' })
    expect(parseDebugCommand(':switch debug-1')).toEqual({ name: 'switch', sessionId: 'debug-1' })
  })

  it('rejects an unknown command and a malformed breakpoint', () => {
    expect(() => parseDebugCommand(':wat')).toThrow(expect.objectContaining({ code: 'DEBUG_UNKNOWN_OPERATION' }))
    expect(() => parseDebugCommand(':break nope')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
  })

  it('parses every documented command shape', () => {
    expect(parseDebugCommand(':run')).toEqual({ name: 'run' })
    expect(parseDebugCommand(':run node-watch')).toEqual({ name: 'run', config: 'node-watch' })
    expect(parseDebugCommand(':attach 4321')).toEqual({ name: 'attach', target: '4321' })
    expect(parseDebugCommand(':break src/a.ts:4')).toEqual({ name: 'break', file: 'src/a.ts', line: 4 })
    expect(parseDebugCommand(':break src/a.ts:4 if x>1 log hit {x}'))
      .toEqual({ name: 'break', file: 'src/a.ts', line: 4, condition: 'x>1', logMessage: 'hit {x}' })
    expect(parseDebugCommand(':break off src/a.ts:4')).toEqual({ name: 'break-off', file: 'src/a.ts', line: 4 })
    expect(parseDebugCommand(':exception')).toEqual({ name: 'exception' })
    expect(parseDebugCommand(':exception uncaught')).toEqual({ name: 'exception', filter: 'uncaught' })
    expect(parseDebugCommand(':pause')).toEqual({ name: 'pause' })
    expect(parseDebugCommand(':continue')).toEqual({ name: 'continue' })
    expect(parseDebugCommand(':step')).toEqual({ name: 'step' })
    expect(parseDebugCommand(':out')).toEqual({ name: 'out' })
    expect(parseDebugCommand(':back')).toEqual({ name: 'back' })
    expect(parseDebugCommand(':bt')).toEqual({ name: 'bt' })
    expect(parseDebugCommand(':bt 2')).toEqual({ name: 'bt', thread: '2' })
    expect(parseDebugCommand(':frame 1')).toEqual({ name: 'frame', index: 1 })
    expect(parseDebugCommand(':vars')).toEqual({ name: 'vars' })
    expect(parseDebugCommand(':eval x + 1')).toEqual({ name: 'eval', expression: 'x + 1' })
    expect(parseDebugCommand(':watch len(items)')).toEqual({ name: 'watch', expression: 'len(items)' })
    expect(parseDebugCommand(':threads')).toEqual({ name: 'threads' })
    expect(parseDebugCommand(':sessions')).toEqual({ name: 'sessions' })
    expect(parseDebugCommand(':terminate')).toEqual({ name: 'terminate' })
    expect(parseDebugCommand(':disconnect')).toEqual({ name: 'disconnect' })
    expect(parseDebugCommand(':adapter list')).toEqual({ name: 'adapter-list' })
    expect(parseDebugCommand(':adapter install node')).toEqual({ name: 'adapter-install', providerId: 'node' })
    expect(parseDebugCommand(':chat')).toEqual({ name: 'chat' })
    expect(parseDebugCommand(':debug')).toEqual({ name: 'debug' })
    expect(parseDebugCommand(':split')).toEqual({ name: 'split' })
    expect(parseDebugCommand(':expand 2')).toEqual({ name: 'expand', index: 2 })
    expect(parseDebugCommand(':help')).toEqual({ name: 'help' })
    expect(parseDebugCommand(':quit')).toEqual({ name: 'quit' })
  })

  it('accepts the command name without the colon prefix and around extra whitespace', () => {
    expect(parseDebugCommand('sessions')).toEqual({ name: 'sessions' })
    expect(parseDebugCommand('  :vars  ')).toEqual({ name: 'vars' })
  })

  it('rejects malformed arguments with DEBUG_INVALID_CONFIG', () => {
    expect(() => parseDebugCommand('')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':continue now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':break src/a.ts:0')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':break src/a.ts:x')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':break src/a.ts:4 if')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':break src/a.ts:4 log')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':break src/a.ts:4 if a if b')).not.toThrow()
    expect(parseDebugCommand(':break src/a.ts:4 if a if b')).toMatchObject({ condition: 'a if b' })
    expect(parseDebugCommand(':break src/a.ts:4 log a if b')).toMatchObject({ logMessage: 'a if b' })
    expect(() => parseDebugCommand(':break src/a.ts:4 junk')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':break off')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':break off src/a.ts:4 extra')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':frame x')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':expand x')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':switch')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':eval')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':watch')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':attach')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':attach 1 2')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':bt 1 2')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':sessions now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':terminate now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':disconnect now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':pause now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':step now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':out now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':back now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':vars now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':threads now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':chat now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':debug now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':split now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':help now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':quit now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':adapter')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':adapter list now')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':adapter install')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':adapter install node extra')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':adapter wat')).toThrow(expect.objectContaining({ code: 'DEBUG_UNKNOWN_OPERATION' }))
    expect(() => parseDebugCommand(':run a b')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
    expect(() => parseDebugCommand(':exception a b')).toThrow(expect.objectContaining({ code: 'DEBUG_INVALID_CONFIG' }))
  })

  it('maps the debug function keys to their command lines', () => {
    expect(DEBUG_KEY_COMMANDS['f5']).toBe(':continue')
    expect(DEBUG_KEY_COMMANDS['shift-f5']).toBe(':pause')
    expect(DEBUG_KEY_COMMANDS['f9']).toBe(':break')
    expect(DEBUG_KEY_COMMANDS['f10']).toBe(':next')
    expect(DEBUG_KEY_COMMANDS['f11']).toBe(':step')
    expect(DEBUG_KEY_COMMANDS['shift-f11']).toBe(':out')
  })
})
